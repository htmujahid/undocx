export function RegeneratePlayground() {
  const [active, setActive] = useState<number | null>(null);
  const [kept, setKept] = useState<number | null>(null);
  const diff = active === null ? null : instructions[active].diff;

  return (
    <Sheet>
      <SheetChrome title={title}>
        <span>Draft · 3 of 6</span>
      </SheetChrome>
      <SheetPage>
        <SectionLabel number="3">Scope of work</SectionLabel>
        <p className={cn(paragraphClass, dimClass)}>{before}</p>
        <div className="mb-3 flex flex-wrap items-center gap-2" role="group" aria-label="Instruction">
          <span className="text-sm text-muted-foreground">Rewrite with:</span>
          {instructions.map((item, index) => (
            <Toggle
              key={item.label}
              pressed={active === index}
              onPressedChange={(pressed) => {
                setActive(pressed ? index : null);
                setKept(null);
              }}
            >
              {item.label}
            </Toggle>
          ))}
        </div>
        {kept !== null ? <Instruction label="Kept">{instructions[kept].label}</Instruction> : null}
        <p className={paragraphClass} aria-live="polite">
          {diff === null
            ? original
            : diff.map((part, index) =>
                part.kind === "remove" ? (
                  kept === null ? (
                    <del key={index} className={removedClass}>
                      {part.text}
                    </del>
                  ) : null
                ) : part.kind === "add" ? (
                  <ins key={index} className={kept === null ? addedClass : "no-underline"}>
                    {part.text}
                  </ins>
                ) : (
                  <span key={index}>{part.text}</span>
                ),
              )}
        </p>
        {diff !== null && kept === null ? (
          <div className="mb-4 flex gap-2">
            <Button size="sm" variant="primary" onClick={() => setKept(active)}>
              Keep
            </Button>
            <Button size="sm" onClick={() => setActive(null)}>
              Undo
            </Button>
          </div>
        ) : null}
        <p className={cn(paragraphClass, dimClass)}>{after}</p>
      </SheetPage>
    </Sheet>
  );
}
