"use client";

import { useState } from "react";
import { Button } from "~@/components/ui/button";
import { AssistantIcon, ClaimsCheckIcon, ColumnsIcon, NoteIcon, RefreshCwIcon } from "~@/components/ui/icons";
import { cn } from "~@/lib/utils";
import { Instruction, Sheet, SheetChrome, SheetPage, addedClass, paragraphClass, removedClass } from "../../_components/doc";

const before = "At the moment, customers receive a confirmation email that is generated by the payment provider and does not mention the shop by name.";

const rewrites = [
  { label: "Cut to half the length", after: "Today's confirmation email comes from the payment provider and never names the shop." },
  { label: "More direct", after: "The payment provider sends the confirmation email, and it does not say who the shop is." },
  { label: "Warmer", after: "Right now the confirmation email comes from the payment provider, so it never says hello from the shop." },
];

type Mode = "idle" | "selected" | "rewrite" | "done" | "noted";

const buttonClass = "inline-flex h-8 items-center gap-1.5 rounded-md px-2 text-sm text-foreground outline-none hover:bg-muted focus-visible:outline-2 focus-visible:outline-offset-1 focus-visible:outline-ring [&_svg]:size-4";

export function SelectionToolbarPlayground() {
  const [mode, setMode] = useState<Mode>("selected");
  const [picked, setPicked] = useState(rewrites[0]);
  const isSelected = mode === "selected" || mode === "rewrite";

  return (
    <Sheet>
      <SheetChrome title="Proposal: a new online store for Marlow & Finch">
        <span>Draft · 3 of 6</span>
      </SheetChrome>
      <SheetPage className="min-h-72">
        <p className={cn(paragraphClass, "relative mb-0")}>
          Order emails.{" "}
          {mode === "done" ? (
            <>
              <del className={removedClass}>{before}</del> <ins className={addedClass}>{picked.after}</ins>
            </>
          ) : (
            <span role="button" tabIndex={0} aria-pressed={isSelected} onClick={() => setMode(isSelected ? "idle" : "selected")} onKeyDown={(event) => { if (event.key === "Enter" || event.key === " ") { event.preventDefault(); setMode(isSelected ? "idle" : "selected"); } }} className={cn("cursor-text rounded-xs outline-none box-decoration-clone focus-visible:outline-2 focus-visible:outline-offset-1 focus-visible:outline-ring", isSelected ? "bg-primary/20" : mode === "noted" ? "bg-primary/12 shadow-[0_2px_0_0_color-mix(in_oklab,var(--primary)_45%,transparent)]" : "hover:bg-muted")}>
              {before}
            </span>
          )}{" "}
          We will write and design three emails.
        </p>
        {isSelected ? (
          <div className="mt-3 flex max-w-full flex-col items-start gap-2">
            <div role="toolbar" aria-label="Selection" className="flex flex-wrap items-center gap-0.5 rounded-lg border border-input bg-popover p-1 shadow-md">
              <button type="button" aria-expanded={mode === "rewrite"} onClick={() => setMode(mode === "rewrite" ? "selected" : "rewrite")} className={cn(buttonClass, "text-primary-deep hover:bg-primary/10", mode === "rewrite" && "bg-primary/10")}>
                <RefreshCwIcon />
                Rewrite
              </button>
              <button type="button" aria-label="Ask Undocx about this" className={buttonClass}>
                <AssistantIcon />
              </button>
              <button type="button" aria-label="Three variations" className={buttonClass}>
                <ColumnsIcon />
              </button>
              <button type="button" aria-label="Check claims" className={buttonClass}>
                <ClaimsCheckIcon />
              </button>
              <span aria-hidden="true" className="mx-1 h-5 w-px bg-border" />
              <button type="button" aria-label="Add a note" onClick={() => setMode("noted")} className={buttonClass}>
                <NoteIcon />
              </button>
            </div>
            {mode === "rewrite" ? (
              <ul className="m-0 grid w-full max-w-xs list-none gap-0.5 rounded-lg border border-input bg-popover p-1 shadow-md">
                {rewrites.map((rewrite) => (
                  <li key={rewrite.label}>
                    <button
                      type="button"
                      onClick={() => {
                        setPicked(rewrite);
                        setMode("done");
                      }}
                      className="w-full rounded-md px-2 py-1.5 text-left text-sm text-foreground outline-none hover:bg-muted focus-visible:outline-2 focus-visible:outline-ring"
                    >
                      {rewrite.label}
                    </button>
                  </li>
                ))}
              </ul>
            ) : null}
          </div>
        ) : null}
        {mode === "idle" ? <p className="m-0 mt-4 text-sm text-muted-foreground">Select the sentence to bring up the toolbar.</p> : null}
        {mode === "done" ? (
          <div className="mt-4 flex flex-wrap items-center gap-3">
            <Instruction label="Rewrote selection with">{picked.label}</Instruction>
            <Button size="sm" variant="ghost" onClick={() => setMode("selected")}>
              Reset
            </Button>
          </div>
        ) : null}
        {mode === "noted" ? (
          <div className="mt-4 flex flex-wrap items-center gap-3">
            <p className="m-0 text-sm text-muted-foreground">Note started on this sentence. It opens in the Notes tab, and nothing else in the paragraph changed.</p>
            <Button size="sm" variant="ghost" onClick={() => setMode("selected")}>
              Reset
            </Button>
          </div>
        ) : null}
      </SheetPage>
    </Sheet>
  );
}
